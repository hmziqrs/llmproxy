/// Config directory: `~/.config/llm-proxy/`.
///
/// Falls back to `./.config/llm-proxy/` (relative to current working directory)
/// when `$HOME` and `$USERPROFILE` are both unset. This is unlikely in practice
/// but avoids a panic. A warning is emitted to stderr in that case since the
/// resolved path depends on the current working directory.
fn config_dir() -> PathBuf {
    let home = home_env::home_dir();
    if home.is_none() {
        eprintln!(
            "warning: HOME and USERPROFILE are both unset; using relative \
             config path (depends on current working directory)"
        );
    }
    home.unwrap_or_else(|| PathBuf::from("."))
        .join(".config")
        .join("llm-proxy")
}

/// Config file path: `~/.config/llm-proxy/config.toml`.
fn default_config_path() -> PathBuf {
    config_dir().join("config.toml")
}

/// PID file path: `~/.config/llm-proxy/llm-proxy.pid`.
fn pid_file_path() -> PathBuf {
    config_dir().join("llm-proxy.pid")
}

/// Resolve the config file path.
///
/// Priority:
/// 1. Explicit CLI `--config` argument
/// 2. `$LLM_PROXY_CONFIG` env var
/// 3. Default path `~/.config/llm-proxy/config.toml`
fn resolve_config(cli_path: Option<&std::path::Path>) -> PathBuf {
    // 1. Explicit CLI path always wins.
    if let Some(p) = cli_path {
        return p.to_path_buf();
    }
    // 2. Preferred env var.
    if let Ok(p) = std::env::var("LLM_PROXY_CONFIG") {
        if !p.is_empty() {
            return PathBuf::from(p);
        }
    }
    default_config_path()
}

/// Returns the providers directory path, which is always `providers/`
/// next to the config file.
///
/// Falls back to `./providers` if the config path has no parent directory
/// (e.g. bare filename `config.toml` with no directory component).
fn providers_dir_for(config_path: &std::path::Path) -> PathBuf {
    config_path
        .parent()
        .unwrap_or(std::path::Path::new("."))
        .join("providers")
}

/// Returns the launchd plist path on macOS.
///
/// Falls back to `./com.llm-proxy.plist` if home directory cannot be determined.
#[cfg(target_os = "macos")]
fn launchd_plist_path() -> PathBuf {
    home_env::home_dir()
        .map(|h| {
            h.join("Library")
                .join("LaunchAgents")
                .join("com.llm-proxy.plist")
        })
        .unwrap_or_else(|| PathBuf::from("com.llm-proxy.plist"))
}

/// Returns the XDG autostart directory on Linux.
///
/// Falls back to `./.config/autostart` if home directory cannot be determined.
#[cfg(target_os = "linux")]
fn linux_autostart_dir() -> PathBuf {
    home_env::home_dir()
        .map(|h| h.join(".config").join("autostart"))
        .unwrap_or_else(|| PathBuf::from(".config/autostart"))
}

// ---------------------------------------------------------------------------
// PID file helpers (delegating to core::PidManager)
// ---------------------------------------------------------------------------

/// Build a [`PidManager`] for the default config directory.
fn pid_manager() -> llm_proxy_core::PidManager {
    llm_proxy_core::PidManager::new(config_dir())
}

/// Read the PID from the PID file. Returns `None` if the file does not exist.
///
/// Validates that the parsed PID is non-zero and fits in `i32` to catch
/// corrupt/stale PID files and prevent undefined behavior when passing the
/// PID to `libc::kill()`.
fn read_pid() -> Result<Option<u32>> {
    let mgr = pid_manager();
    let pid = mgr.read_pid()?;
    if let Some(p) = pid {
        if p == 0 {
            bail!("invalid PID 0 in PID file");
        }
        if p > i32::MAX as u32 {
            bail!("PID {p} exceeds i32::MAX -- cannot be a valid process ID");
        }
    }
    Ok(pid)
}

/// Atomically create the PID file with exclusive ownership.
///
/// Uses `create_new(true)` so the file is created exclusively -- if another
/// process already created it, the call fails and we return the OS error.
/// This eliminates the TOCTOU race between checking for a stale PID and
/// writing the new one. After creation, restrictive permissions (0600) are
/// applied.
fn write_pid() -> Result<()> {
    let dir = config_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("creating directory {}", dir.display()))?;
    set_private_dir_permissions(&dir)?;
    let path = pid_file_path();
    let pid = std::process::id();
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .with_context(|| format!("creating PID file {}", path.display()))?;
    write!(f, "{pid}").with_context(|| format!("writing PID file {}", path.display()))?;
    // Set restrictive permissions on the PID file.
    set_private_permissions(&path)?;
    info!(pid, "wrote PID file");
    Ok(())
}

/// Write a specific PID value to the PID file.
///
/// Used by the daemon parent to write the child PID before detaching.
/// Applies restrictive permissions (0600) after creation.
fn write_pid_value(pid: u32) -> Result<()> {
    let dir = config_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("creating directory {}", dir.display()))?;
    set_private_dir_permissions(&dir)?;
    let path = pid_file_path();
    let mut f = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .with_context(|| format!("creating PID file {}", path.display()))?;
    write!(f, "{pid}").with_context(|| format!("writing PID file {}", path.display()))?;
    set_private_permissions(&path)?;
    info!(pid, "wrote PID file");
    Ok(())
}

/// Remove the PID file.
fn remove_pid() -> Result<()> {
    pid_manager().remove_pid()
}

/// Check if a process with the given PID is running.
///
/// Delegates to [`PidManager::is_process_running`]. Returns `false` for
/// PID 0 (which would otherwise signal the entire process group on Unix)
/// and on non-Unix platforms where process signaling is unavailable.
fn is_process_running(pid: u32) -> bool {
    if pid == 0 {
        return false;
    }
    llm_proxy_core::PidManager::is_process_running(pid)
}

// ---------------------------------------------------------------------------
// Config extension validation
// ---------------------------------------------------------------------------

/// Check if a path points to a TOML config file.
fn is_toml_config(path: &std::path::Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| e.eq_ignore_ascii_case("toml"))
}

/// Validate that the config file path has a supported extension.
///
/// Rejects non-TOML paths with an unsupported-extension error.
fn validate_toml_extension(path: &std::path::Path) -> Result<()> {
    if !is_toml_config(path) {
        bail!(
            "unsupported config file extension: {:?} (expected .toml)",
            path.extension()
                .map(|e| e.to_string_lossy())
                .unwrap_or_else(|| std::borrow::Cow::Borrowed("(none)"))
        );
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

#[tokio::main]
async fn main() -> Result<()> {
    let cli = Cli::parse();

    match cli.command {
        Commands::Serve {
            config,
            port,
            background,
            daemonize,
        } => cmd_serve(config, port, background, daemonize).await,
        Commands::Stop => cmd_stop(),
        Commands::Status => cmd_status(),
        Commands::Init => cmd_init(),
        Commands::Validate { config } => cmd_validate(config),
        Commands::Models {
            config,
            provider,
            live,
            write_catalog,
            require_success,
        } => cmd_models(config, provider, live, write_catalog, require_success).await,
        Commands::Autostart { action } => match action {
            AutostartAction::Enable { config, port } => cmd_autostart_enable(config, port),
            AutostartAction::Disable => cmd_autostart_disable(),
            AutostartAction::Status => cmd_autostart_status(),
        },
    }
}

