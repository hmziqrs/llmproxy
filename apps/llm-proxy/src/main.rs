/// Run the `serve` command.
///
/// Requires TOML config. JSON config is rejected with a migration error.
/// `$OC_GO_CC_CONFIG` alone emits the migration error. An explicit TOML
/// `--config` or `$LLM_PROXY_CONFIG` wins over `$OC_GO_CC_CONFIG`.
async fn cmd_serve(
    config_path: Option<PathBuf>,
    port_override: Option<u16>,
    background: bool,
    daemonize: bool,
) -> Result<()> {
    // If background mode requested, spawn self as child with --daemonize.
    if background && !daemonize {
        return spawn_daemon(config_path, port_override);
    }

    init_tracing();

    // Resolve config file path.
    let (path, legacy_env) = resolve_serve_config(config_path.as_deref());

    // Reject JSON config and non-TOML extensions with migration/unsupported error.
    validate_toml_extension(&path)?;

    // If only $OC_GO_CC_CONFIG is set (no explicit --config, no $LLM_PROXY_CONFIG),
    // print migration error and exit. This rejects $OC_GO_CC_CONFIG regardless of
    // file extension: even TOML files via this env var are rejected to force users
    // to migrate to the preferred $LLM_PROXY_CONFIG or explicit --config.
    if legacy_env {
        bail!("{}", MIGRATION_ERROR);
    }

    // Build shared infrastructure.
    let adapter_registry = ProviderAdapterRegistry::builtin();
    let proxy_client = ProxyClient::new();

    // Check if already running.
    if let Some(pid) = read_pid()? {
        if is_process_running(pid) {
            bail!(
                "server already running with PID {} (PID file: {})",
                pid,
                pid_file_path().display()
            );
        }
        info!("stale PID file found, cleaning up");
        remove_pid()?;
    }

    // Write PID file.
    write_pid()?;

    // Ensure PID file is cleaned up on shutdown.
    let pid_path = pid_file_path();
    let cleanup = async move {
        if let Err(e) = std::fs::remove_file(&pid_path) {
            tracing::warn!(error = %e, "failed to remove PID file during shutdown");
        }
    };

    // Load TOML config and build state (consumes adapter_registry and proxy_client).
    let state = load_toml_state(&path, adapter_registry, proxy_client, port_override)?;

    let bind_addr = state.bind_address();
    let app = build_router(state);

    let listener = TcpListener::bind(bind_addr)
        .await
        .with_context(|| format!("binding to {bind_addr}"))?;
    info!(
        addr = %listener.local_addr()?,
        version = env!("CARGO_PKG_VERSION"),
        "llm-proxy listening"
    );

    // Serve with graceful shutdown.
    let result = axum::serve(listener, app)
        .with_graceful_shutdown(shutdown_signal())
        .await;

    cleanup.await;

    match result {
        Ok(()) => {
            info!("server stopped cleanly");
            Ok(())
        }
        Err(e) => {
            tracing::error!(error = %e, "server error");
            Err(anyhow::anyhow!("server error: {}", e))
        }
    }
}

/// Spawn the current binary as a background daemon.
fn spawn_daemon(config_path: Option<PathBuf>, port_override: Option<u16>) -> Result<()> {
    let exe = std::env::current_exe().with_context(|| "resolving current executable")?;
    let mut cmd = std::process::Command::new(&exe);
    cmd.arg("serve").arg("--daemonize");

    if let Some(ref p) = config_path {
        cmd.arg("--config").arg(p);
    }
    if let Some(p) = port_override {
        cmd.arg("--port").arg(p.to_string());
    }

    // Detach from terminal.
    #[cfg(unix)]
    {
        use std::os::unix::process::CommandExt;
        cmd.process_group(0);
        // Redirect stdout/stderr to a log file.
        let log_path = config_dir().join("llm-proxy.log");
        let log_file = std::fs::File::options()
            .create(true)
            .append(true)
            .open(&log_path)
            .with_context(|| format!("opening log file {}", log_path.display()))?;
        cmd.stdout(
            log_file
                .try_clone()
                .with_context(|| "cloning log file handle")?,
        );
        cmd.stderr(log_file);
    }

    #[cfg(not(unix))]
    {
        println!(
            "warning: daemon log redirection is not supported on this platform; \
                   output will be lost"
        );
    }

    let mut child = cmd.spawn().with_context(|| "spawning daemon process")?;

    let pid = child.id();
    println!("llm-proxy started in background (PID {pid})");
    println!("  config dir: {}", config_dir().display());
    println!(
        "  log file:   {}",
        config_dir().join("llm-proxy.log").display()
    );

    // Detach from child so we don't wait on it.
    if let Err(e) = child.try_wait() {
        tracing::warn!(error = %e, "failed to check daemon child status");
    }

    Ok(())
}

/// Run the `stop` command.
fn cmd_stop() -> Result<()> {
    match read_pid()? {
        Some(pid) => {
            if !is_process_running(pid) {
                println!("server not running (stale PID {pid})");
                remove_pid()?;
                return Ok(());
            }

            #[cfg(unix)]
            {
                // Send SIGTERM.
                let ret = unsafe { libc::kill(pid as i32, libc::SIGTERM) };
                if ret != 0 {
                    bail!("failed to send SIGTERM to PID {pid}");
                }
            }

            println!("sent SIGTERM to PID {pid}");

            // Wait briefly for process to exit.
            for _ in 0..10 {
                if !is_process_running(pid) {
                    remove_pid()?;
                    println!("server stopped");
                    return Ok(());
                }
                std::thread::sleep(std::time::Duration::from_millis(200));
            }

            // Force kill if still running.
            #[cfg(unix)]
            {
                let ret = unsafe { libc::kill(pid as i32, libc::SIGKILL) };
                if ret != 0 {
                    bail!("failed to send SIGKILL to PID {pid}");
                }
            }
            remove_pid()?;
            println!("server force-stopped (PID {pid})");
            Ok(())
        }
        None => {
            println!("no PID file found -- server not running");
            Ok(())
        }
    }
}

/// Run the `status` command.
fn cmd_status() -> Result<()> {
    match read_pid()? {
        Some(pid) => {
            if is_process_running(pid) {
                println!("server is running (PID {pid})");
                // Try to load actual bind address from config.
                let config_path = default_config_path();
                if config_path.exists() {
                    if let Ok(cfg) = load_app_config(&config_path) {
                        println!("  listen: {}", cfg.server.bind);
                    } else {
                        println!("  listen: (could not parse config)");
                    }
                } else {
                    println!("  listen: (config not found: {})", config_path.display());
                }
                println!("  config: {}", config_path.display());
            } else {
                println!("server not running (stale PID {pid})");
            }
            Ok(())
        }
        None => {
            println!("server not running (no PID file)");
            Ok(())
        }
    }
}

/// Run the `init` command.
///
/// Creates:
/// - `config.toml` in the config directory
/// - `providers/opencode-go.toml` next to the config
/// - `providers/opencode-zen.toml` next to the config
///
/// Does NOT write:
/// - fallback/scenario JSON
/// - sampling/tool/reasoning/cache/stream overrides
fn cmd_init() -> Result<()> {
    let config_path = default_config_path();
    if config_path.exists() {
        bail!("config file already exists at {}", config_path.display());
    }

    let dir = config_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("creating directory {}", dir.display()))?;

    // Write main config.toml with restrictive permissions (contains env var references).
    let mut f = std::fs::File::create(&config_path)
        .with_context(|| format!("creating {}", config_path.display()))?;
    f.write_all(DEFAULT_CONFIG_TOML.as_bytes())
        .with_context(|| format!("writing {}", config_path.display()))?;
    set_private_permissions(&config_path)?;
    println!("created config at {}", config_path.display());

    // Create providers directory.
    let providers_dir = providers_dir_for(&config_path);
    std::fs::create_dir_all(&providers_dir)
        .with_context(|| format!("creating directory {}", providers_dir.display()))?;

    // Write opencode-go provider with restrictive permissions.
    let go_path = providers_dir.join("opencode-go.toml");
    let mut f = std::fs::File::create(&go_path)
        .with_context(|| format!("creating {}", go_path.display()))?;
    f.write_all(DEFAULT_PROVIDER_OPENCODE_GO.as_bytes())
        .with_context(|| format!("writing {}", go_path.display()))?;
    set_private_permissions(&go_path)?;
    println!("created provider config at {}", go_path.display());

    // Write opencode-zen provider with restrictive permissions.
    let zen_path = providers_dir.join("opencode-zen.toml");
    let mut f = std::fs::File::create(&zen_path)
        .with_context(|| format!("creating {}", zen_path.display()))?;
    f.write_all(DEFAULT_PROVIDER_OPENCODE_ZEN.as_bytes())
        .with_context(|| format!("writing {}", zen_path.display()))?;
    set_private_permissions(&zen_path)?;
    println!("created provider config at {}", zen_path.display());

    println!();
    println!("Next steps:");
    println!("  1. Set API keys via environment variables:");
    println!("     export LLM_PROXY_OPENCODE_GO_KEY=your-go-key");
    println!("     export LLM_PROXY_OPENCODE_ZEN_KEY=your-zen-key");
    println!("  2. Run `llm-proxy validate` to check your config");
    println!("  3. Run `llm-proxy serve` to start the proxy");

    Ok(())
}

/// Run the `validate` command.
///
/// Loads main TOML, loads provider files, validates provider adapter protocols
/// against builtins, and prints provider route table.
fn cmd_validate(config_path: Option<PathBuf>) -> Result<()> {
    let path = resolve_config(config_path.as_deref());

    // Reject JSON config and non-TOML extensions.
    validate_toml_extension(&path)?;

    println!("validating config: {}", path.display());

    let app_config: AppConfig = load_app_config(&path)
        .with_context(|| format!("loading TOML config from {}", path.display()))?;

    // Print settings summary.
    println!();
    println!("=== Server Configuration ===");
    println!("  bind:            {}", app_config.server.bind);
    println!(
        "  request_timeout: {}s",
        app_config.server.request_timeout.as_secs()
    );
    println!("  log_level:       {}", app_config.server.log_level);
    println!("  hot_reload:      {}", app_config.server.hot_reload);
    println!("  server_name:     {}", app_config.server.server_name);

    // Load and validate providers.
    let providers_dir = providers_dir_for(&path);
    let registry = if providers_dir.exists() {
        ProviderRegistry::load_from_dir(&providers_dir)
            .with_context(|| format!("loading providers from {}", providers_dir.display()))?
    } else {
        ProviderRegistry::from_providers(vec![])
            .with_context(|| "building empty provider registry")?
    };

    // Validate provider protocols against builtin adapters.
    let adapter_registry = ProviderAdapterRegistry::builtin();
    let known_protocols = adapter_registry.protocol_names();
    registry
        .validate_protocols(known_protocols)
        .with_context(|| "validating provider protocols")?;

    println!();
    println!("=== Providers ({} loaded) ===", registry.len());
    if registry.is_empty() {
        println!("  (none)");
    } else {
        for provider in registry.iter() {
            println!(
                "  {} ({} adapters, {} models)",
                provider.name,
                provider.adapters.len(),
                provider.models.len()
            );
        }
    }

    // Print provider route table: provider -> model -> adapter/protocol
    println!();
    println!("=== Provider Routes ===");
    if registry.is_empty() {
        println!("  (no providers loaded)");
    } else {
        let mut route_errors: Vec<String> = Vec::new();
        for provider in registry.iter() {
            println!("{}:", provider.name);
            if provider.models.is_empty() {
                println!("  (no models configured)");
            } else {
                for (model_name, model_cfg) in &provider.models {
                    match provider.adapters.get(&model_cfg.adapter) {
                        Some(adapter) => {
                            println!(
                                "  {} -> {}/{}",
                                model_name, model_cfg.adapter, adapter.protocol
                            );
                        }
                        None => {
                            let msg = format!(
                                "  {} -> ERROR: unknown adapter \"{}\"",
                                model_name, model_cfg.adapter
                            );
                            println!("{}", msg);
                            route_errors.push(msg);
                        }
                    }
                }
            }
        }

        if !route_errors.is_empty() {
            bail!(
                "config has {} route resolution error(s)",
                route_errors.len()
            );
        }
    }

    println!();
    println!("Config is valid!");
    Ok(())
}

/// Run the `models` command.
///
/// Lists provider-scoped models from provider config files. Each provider's
/// model-to-adapter mappings are displayed grouped by provider name.
fn cmd_models(config_path: Option<PathBuf>) -> Result<()> {
    let path = resolve_config(config_path.as_deref());

    // Reject JSON config and non-TOML extensions.
    validate_toml_extension(&path)?;

    // Load providers from the providers/ directory next to the config.
    let providers_dir = providers_dir_for(&path);
    let registry = if providers_dir.exists() {
        ProviderRegistry::load_from_dir(&providers_dir)
            .with_context(|| format!("loading providers from {}", providers_dir.display()))?
    } else {
        ProviderRegistry::from_providers(vec![])
            .with_context(|| "building empty provider registry")?
    };

    if registry.is_empty() {
        println!("No providers configured.");
        println!("Add provider files to {}", providers_dir.display());
        return Ok(());
    }

    println!("Provider-scoped models (from {}):", providers_dir.display());
    println!();
    for provider in registry.iter() {
        if provider.models.is_empty() {
            println!("  {}:", provider.name);
            println!("    (no models configured, all models sent as-is to upstream)");
        } else {
            println!("  {}:", provider.name);
            for (model_name, model_cfg) in &provider.models {
                println!("    {} -> {}", model_name, model_cfg.adapter);
            }
        }
    }

    Ok(())
}

/// Run the `autostart enable` command.
fn cmd_autostart_enable(config_path: Option<PathBuf>, port: Option<u16>) -> Result<()> {
    let dir = config_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("creating directory {}", dir.display()))?;

    let exe = std::env::current_exe().with_context(|| "resolving current executable")?;
    // Build args as strings for plist/desktop entry display. Lossy conversion is
    // acceptable here because these are display-only strings that are XML-escaped
    // by format_plist(). Non-UTF-8 paths are rare and the lossy replacement is
    // sufficient for auto-start purposes.
    let mut args = vec![exe.to_string_lossy().to_string(), "serve".to_string()];

    if let Some(ref p) = config_path {
        args.push("--config".to_string());
        args.push(p.to_string_lossy().to_string());
    }
    if let Some(p) = port {
        args.push("--port".to_string());
        args.push(p.to_string());
    }

    #[cfg(target_os = "macos")]
    {
        let plist_content = format_plist(&args.join(" "));
        let plist_path = launchd_plist_path();

        let plist_dir = plist_path
            .parent()
            .with_context(|| format!("invalid plist path: {}", plist_path.display()))?;
        std::fs::create_dir_all(plist_dir)
            .with_context(|| format!("creating {}", plist_dir.display()))?;

        std::fs::write(&plist_path, plist_content)
            .with_context(|| format!("writing {}", plist_path.display()))?;
        // Set restrictive permissions on the plist file.
        set_private_permissions(&plist_path)?;

        println!("created launchd plist at {}", plist_path.display());
        println!("run: launchctl load {}", plist_path.display());
    }

    #[cfg(target_os = "linux")]
    {
        let desktop_content = format_desktop_entry(&args.join(" "));
        let autostart_dir = linux_autostart_dir();
        std::fs::create_dir_all(&autostart_dir)
            .with_context(|| format!("creating {}", autostart_dir.display()))?;
        let desktop_path = autostart_dir.join("llm-proxy.desktop");
        std::fs::write(&desktop_path, desktop_content)
            .with_context(|| format!("writing {}", desktop_path.display()))?;
        // Set restrictive permissions on the desktop entry.
        set_private_permissions(&desktop_path)?;
        println!("created desktop entry at {}", desktop_path.display());
    }

    #[cfg(not(any(target_os = "macos", target_os = "linux")))]
    {
        println!("auto-start is not supported on this platform");
        println!("add this command to your shell startup script:");
        println!("  {}", args.join(" "));
    }

    Ok(())
}

/// Run the `autostart disable` command.
fn cmd_autostart_disable() -> Result<()> {
    #[cfg(target_os = "macos")]
    {
        let plist_path = launchd_plist_path();

        if plist_path.exists() {
            let _ = std::process::Command::new("launchctl")
                .args(["unload", &plist_path.to_string_lossy()])
                .output();
            std::fs::remove_file(&plist_path)
                .with_context(|| format!("removing {}", plist_path.display()))?;
            println!("removed launchd plist");
        } else {
            println!("no launchd plist found");
        }
    }

    #[cfg(target_os = "linux")]
    {
        let autostart_dir = linux_autostart_dir();
        let desktop_path = autostart_dir.join("llm-proxy.desktop");
        if desktop_path.exists() {
            std::fs::remove_file(&desktop_path)
                .with_context(|| format!("removing {}", desktop_path.display()))?;
            println!("removed desktop entry");
        } else {
            println!("no desktop entry found");
        }
    }

    #[cfg(not(any(target_os = "macos", target_os = "linux")))]
    {
        println!("auto-start is not supported on this platform");
    }

    Ok(())
}

