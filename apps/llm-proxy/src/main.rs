/// Read the PID from the PID file. Returns `None` if the file does not exist.
fn read_pid() -> Result<Option<u32>> {
    let path = pid_file_path();
    if !path.exists() {
        return Ok(None);
    }
    let content = std::fs::read_to_string(&path)
        .with_context(|| format!("reading PID file {}", path.display()))?;
    let pid: u32 = content
        .trim()
        .parse()
        .with_context(|| format!("parsing PID from {}", path.display()))?;
    Ok(Some(pid))
}

/// Write the current PID to the PID file.
fn write_pid() -> Result<()> {
    let dir = config_dir();
    std::fs::create_dir_all(&dir)
        .with_context(|| format!("creating directory {}", dir.display()))?;
    let path = pid_file_path();
    let pid = std::process::id();
    let mut f = std::fs::File::create(&path)
        .with_context(|| format!("creating PID file {}", path.display()))?;
    write!(f, "{pid}").with_context(|| format!("writing PID file {}", path.display()))?;
    info!(pid, "wrote PID file");
    Ok(())
}

/// Remove the PID file.
fn remove_pid() -> Result<()> {
    let path = pid_file_path();
    if path.exists() {
        std::fs::remove_file(&path)
            .with_context(|| format!("removing PID file {}", path.display()))?;
    }
    Ok(())
}

/// Check if a process with the given PID is running.
///
/// On Unix, uses `kill(pid, 0)` which checks process existence without
/// sending a signal. Returns `true` when `kill` returns 0 (process exists
/// and we have permission) OR when it returns -1 with `EPERM` (process
/// exists but we lack permission to signal it). Only returns `false` when
/// `ESRCH` is returned (no such process).
fn is_process_running(pid: u32) -> bool {
    // SAFETY: kill(pid, 0) just checks if the process exists; it does not
    // send a signal on any Unix platform. The pid is validated to be a
    // non-zero positive integer by the caller (read from PID file).
    #[cfg(unix)]
    {
        let ret = unsafe { libc::kill(pid as i32, 0) };
        if ret == 0 {
            return true;
        }
        // EPERM means the process exists but we cannot signal it.
        #[cfg(target_os = "macos")]
        let errno = unsafe { *libc::__error() };
        #[cfg(target_os = "linux")]
        let errno = unsafe { *libc::__errno_location() };
        #[cfg(not(any(target_os = "macos", target_os = "linux")))]
        let errno: i32 = 0; // Assume not EPERM on other Unix platforms.
        errno == libc::EPERM
    }
    #[cfg(not(unix))]
    {
        // Fallback: always assume running on non-Unix.
        let _ = pid;
        true
    }
}

// ---------------------------------------------------------------------------
// Config extension validation
// ---------------------------------------------------------------------------

/// Check if a path points to a JSON config file.
fn is_json_config(path: &std::path::Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| e.eq_ignore_ascii_case("json"))
}

/// Check if a path points to a TOML config file.
fn is_toml_config(path: &std::path::Path) -> bool {
    path.extension()
        .and_then(|e| e.to_str())
        .is_some_and(|e| e.eq_ignore_ascii_case("toml"))
}

/// Validate that the config file path has a supported extension.
///
/// Rejects JSON paths with the migration error and non-TOML paths with an
/// unsupported-extension error. Returns `Ok(())` for `.toml` paths.
fn validate_toml_extension(path: &std::path::Path) -> Result<()> {
    if is_json_config(path) {
        bail!("{}", MIGRATION_ERROR);
    }
    if !is_toml_config(path) {
        bail!(
            "unsupported config file extension: {:?} (expected .toml)",
            path.extension()
                .map(|e| e.to_string_lossy())
                .unwrap_or_else(|| std::borrow::Cow::Borrowed("(none)"))
        );
    }
    Ok(())
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

#[tokio::main]
async fn main() -> Result<()> {
    let cli = Cli::parse();

    match cli.command {
        Commands::Serve {
            config,
            port,
            background,
            daemonize,
        } => cmd_serve(config, port, background, daemonize).await,
        Commands::Stop => cmd_stop(),
        Commands::Status => cmd_status(),
        Commands::Init => cmd_init(),
        Commands::Validate { config } => cmd_validate(config),
        Commands::Models { config } => cmd_models(config),
        Commands::Autostart { action } => match action {
            AutostartAction::Enable { config, port } => cmd_autostart_enable(config, port),
            AutostartAction::Disable => cmd_autostart_disable(),
            AutostartAction::Status => cmd_autostart_status(),
        },
    }
}

